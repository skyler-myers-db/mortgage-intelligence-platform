/**
 * Score anatomy fixtures (wave 3, lane w3-score-anatomy: wow-stage-2,
 * wow-ai-1, wow-stage-3).
 *
 * Nothing here registers by default and there is no registry line: the
 * default GET /api/borrowers/:id/proof (data/leads.ts) is trusted WITH a gap
 * and uses older weights, so score-anatomy.fixture.spec.ts registers these
 * overrides per test with `mockApi.register()`:
 *
 *   - `registerAnatomyProof(mockApi, 'trusted' | 'untrusted')`: the proof
 *     with the live weights (0.35 / 0.30 / 0.15 / 0.10 / 0.10) and the five
 *     deterministic margins; trusted has no gap (the seal renders),
 *     untrusted lists two gaps (it does not);
 *   - `registerRoutedApprove(mockApi, gate?)`: the approve POST answering
 *     with an assignee and a follow-up (the routing line), optionally held
 *     on a RequestGate, plus the ledger read-back;
 *   - `registerExplorerDecisionRows(mockApi)`: an audit explorer page with
 *     one APPROVE row and one VIEW_LEADS row, and the receipt read-back.
 *
 * Every payload is typed against the frontend's own response types and
 * `contractSamples()` exports them for the fixture contract (api-contract
 * lane). Synthetic only: masked ids, `.example` staff, no contact fields.
 */
