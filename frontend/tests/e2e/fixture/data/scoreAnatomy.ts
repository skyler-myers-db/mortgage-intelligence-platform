export function anatomyProof(borrower: Borrower360, kind: AnatomyProofKind): BorrowerProof {
  const trusted = kind === 'trusted';
  const formula = (label: string, source: string) => ({ label, expression: `${label} inputs`, result: label, source });
  return {
    borrower_id: borrower.borrower_id,
    trusted,
    known_data_gaps: trusted ? [] : [...UNTRUSTED_GAPS],
    generated_from: 'mip.gold.borrower_dossier + mip.gold.lead_scores',
    source_refresh_at: `dossier ${SNAPSHOT_AT} / lead_scores ${SNAPSHOT_AT}`,
    opportunity_score: borrower.opportunity_score,
    signal_strength: borrower.confidence,
    signal_strength_note: 'Signal strength is a deterministic average of the five scoring sub-scores.',
    evidence_confidence_note: 'Evidence confidence is row-level source confidence from gold.evidence_events.',
    score_components: components(),
    score_formula: formula('Opportunity score', 'mip.gold.fn_lead_score'),
    signal_strength_formula: formula('Signal strength', 'mip.gold.lead_scores'),
    rate_spread_formula: formula('Rate spread', 'mip.gold.fn_rate_spread'),
    equity_formula: formula('Equity', 'mip.gold.borrower_dossier'),
    ltv_formula: formula('LTV', 'mip.gold.borrower_dossier'),
    offer_code: borrower.recommended_offer_code ?? 'refi',
    offer_label: borrower.recommended_offer,
    offer_branches: [],
    evidence_rows: borrower.evidence_events.map(({ source_table: _table, ...row }) => row),
    source_assets: ['mip.gold.borrower_dossier', 'mip.gold.lead_scores', 'mip.gold.evidence_events'],
    reproduce: [],
    margins: [...ANATOMY_MARGINS],
  };
}

export function registerAnatomyProof(mockApi: MockApi, kind: AnatomyProofKind): void {
  mockApi.register<BorrowerProof | { detail: string }>('GET', '/api/borrowers/:id/proof', ({ params }) => {
    const borrower = borrowerById(params.id);
    if (!borrower) return json({ detail: `Borrower ${params.id} is not in the fixture population.` }, { status: 404 });
    return json<BorrowerProof>(anatomyProof(borrower, kind));
  });
}

/** The routed approve (assignee + follow-up) and its ledger read-back; the POST may be held. */
export function registerRoutedApprove(mockApi: MockApi, gate: RequestGate | null = null): void {
  mockApi.register('POST', '/api/outreach/approve', async () => {
    if (gate) await gate.hold();
    return routedApproveResult();
  });
  mockApi.register('GET', '/api/audit/receipt/:id', ({ params }) =>
    json<DecisionReceipt>(ledgerReceipt(params.id, PRIMARY_BORROWER, 'approved')),
  );
}

