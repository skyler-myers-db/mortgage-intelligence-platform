/** The par every margin quotes: the fixture dossier's market_rate 0.04875 ("vs. par 4.88%"). */
export const ANATOMY_PAR = 'par 4.88%';

const PARTS: ReadonlyArray<readonly [ProofScoreComponent['key'], string, number, number]> = [
  ['economic_incentive', 'Economic incentive', 0.35, 98],
  ['intent_trigger', 'Intent trigger', 0.3, 95],
  ['fit', 'Product fit', 0.15, 70],
  ['relationship', 'Relationship', 0.1, 80],
  ['evidence', 'Evidence coverage', 0.1, 90],
];

function components(): ProofScoreComponent[] {
  return PARTS.map(([key, label, weight, value]) => ({
    key,
    label,
    value,
    weight,
    weighted_points: Math.round(value * weight * 100) / 100,
    explanation: `${label} sub-score from mip.gold.lead_scores.`,
    source_fields: [key === 'economic_incentive' ? 'rate_spread_bps' : 'evidence_ids'],
    fair_lending_note: key === 'fit' ? 'Audit note: this signal supports marketing prioritization, not credit eligibility.' : null,
  }));
}

