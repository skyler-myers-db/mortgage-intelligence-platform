_FORBIDDEN_COPY = re.compile(r"deny|declin|adverse|reason|eligib|credit[- ]?score|today", re.IGNORECASE)


def _case_row(case_id: str) -> dict[str, Any]:
    overrides, _ = _CASES[case_id]
    return {**_BASE_ROW, **overrides}


def _build(row: dict[str, Any]) -> list[ProofMargin]:
    return build_proof_margins(row, dossier_offer=str(row["recommended_offer_code"]))


def _generate() -> dict[str, Any]:
    cases = []
    for case_id, (_, note) in _CASES.items():
        row = _case_row(case_id)
        cases.append({
            "id": case_id,
            "note": note,
            "row": row,
            "margins": [margin.model_dump() for margin in _build(row)],
        })
    return {
        "_generated_by": "PYTHONPATH=. python tests/unit/test_borrower_proof_margins.py --regen",
        "cases": cases,
    }


