def test_golden_file_covers_every_case() -> None:
    assert [case["id"] for case in GOLDEN["cases"]] == list(_CASES)


@pytest.mark.parametrize("case", GOLDEN["cases"], ids=[case["id"] for case in GOLDEN["cases"]])
def test_margins_match_golden(case: dict[str, Any]) -> None:
    assert case["row"] == _case_row(case["id"]), "the golden row drifted from the case table; regenerate"
    assert [margin.model_dump() for margin in _build(case["row"])] == case["margins"], case["note"]


def _golden_margins(case_id: str) -> dict[str, dict[str, Any]]:
    case = next(case for case in GOLDEN["cases"] if case["id"] == case_id)
    return {margin["key"]: margin for margin in case["margins"]}


def test_golden_pins_the_behaviours_the_cases_name() -> None:
    clears = _golden_margins("clears_refi_plus_heloc")
    assert [clears[key]["direction"] for key in clears] == ["clears", "flips", "clears", "flips", "flips"]
    assert clears["par_break_even"]["value_text"] == (
        "Drops below the refi screen if 30-year par rises 13 bps to 5.01%"
    )
    assert _golden_margins("short_heloc")["spread_screen"]["direction"] == "short"
    odd = _golden_margins("half_bps_odd_min_spread")["par_break_even"]["value_text"]
    assert "rises 17 bps" in odd
    assert "falls 9 bps" in _golden_margins("half_bps_short_odd_min_spread")["par_break_even"]["value_text"]
    for case_id in ("gated_paid_off_lien", "gated_at_rate_floor", "gated_at_rate_cap", "spread_drift", "no_par_rate"):
        margins = _golden_margins(case_id)
        assert margins["par_break_even"]["direction"] == "unavailable", case_id
        assert margins["offer_flip_par"]["direction"] == "unavailable", case_id
        assert margins["spread_screen"]["direction"] in {"clears", "short"}, case_id
    purchase = _golden_margins("purchase_listing_holds")
    assert purchase["offer_flip_equity"]["direction"] == "holds"
    assert purchase["offer_flip_par"]["direction"] == "holds"
    assert purchase["offer_flip_par"]["value_text"].startswith("The listing signal selects this offer")
    drift = _golden_margins("offer_drift")
    assert drift["offer_flip_equity"]["direction"] == "unavailable"
    assert drift["offer_flip_par"]["direction"] == "unavailable"
    wide = _golden_margins("holds_wide_spread")
    assert wide["par_break_even"]["direction"] == "holds"
    assert _golden_margins("equity_short_investor")["equity_floor"]["direction"] == "short"


