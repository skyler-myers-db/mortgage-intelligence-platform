@pytest.mark.parametrize(
    "overrides",
    [{}, {"market_rate_fraction": 0.05}, {"current_rate": 0.0}, {"recommended_offer_code": "refi"}],
    ids=["clean", "par_drift", "gated", "offer_drift"],
)
def test_margins_never_change_trusted_or_known_data_gaps(
    overrides: dict[str, Any], monkeypatch: pytest.MonkeyPatch
) -> None:
    row = _mock_proof_row("B-48291", **overrides)
    with_margins = _build_borrower_proof(row)
    monkeypatch.setattr(proof_module, "build_proof_margins", lambda *_args, **_kwargs: [])
    without_margins = _build_borrower_proof(row)

    assert with_margins.margins, "the proof carries margins"
    assert with_margins.trusted == without_margins.trusted
    assert with_margins.known_data_gaps == without_margins.known_data_gaps
    margin_text = {m.value_text for m in with_margins.margins} | {m.threshold for m in with_margins.margins}
    assert not any(text in gap for gap in with_margins.known_data_gaps for text in margin_text)


def test_a_clean_row_stays_trusted_when_its_par_margins_fail_closed() -> None:
    proof = _build_borrower_proof(_mock_proof_row("B-48291", market_rate_fraction=0.05))
    assert proof.trusted is True
    assert proof.known_data_gaps == []
    by_key = {margin.key: margin for margin in proof.margins}
    assert by_key["par_break_even"].direction == "unavailable"


def test_only_equity_and_the_par_derived_spread_are_perturbed(monkeypatch: pytest.MonkeyPatch) -> None:
    calls: list[dict[str, Any]] = []

    def spy(**kwargs: Any) -> str:
        calls.append(kwargs)
        return next_best_offer(**kwargs)

    monkeypatch.setattr(margins_module, "next_best_offer", spy)
    economic = {"rate_spread_bps", "equity_pct"}
    for case_id in _CASES:
        row = _case_row(case_id)
        fixed = {key: value for key, value in _offer_inputs(row)._asdict().items() if key not in economic}
        calls.clear()
        _build(row)
        assert calls, case_id
        for call in calls:
            assert {key: value for key, value in call.items() if key not in economic} == fixed, case_id
        assert len({call["equity_pct"] for call in calls}) > 1 or case_id == "offer_drift"


def test_margin_copy_avoids_credit_decision_vocabulary() -> None:
    texts = [
        text
        for case in GOLDEN["cases"]
        for margin in case["margins"]
        for text in (margin["label"], margin["value_text"], margin["threshold"])
    ]
    for borrower in mock_data.BORROWERS:
        for margin in _build_borrower_proof(_mock_proof_row(borrower.borrower_id)).margins:
            texts.extend((margin.label, margin.value_text, margin.threshold))
    assert texts
    assert [text for text in texts if _FORBIDDEN_COPY.search(text)] == []


def test_margin_sources_are_governed_proof_assets() -> None:
    assets = set(borrower_proof_assets())
    sources = {margin["source"] for case in GOLDEN["cases"] for margin in case["margins"]}
    assert sources
    assert sources <= assets


def test_note_rate_reconstruction_is_exact_for_eighth_point_coupons() -> None:
    coupons = [eighths / 8 for eighths in range(9, 120)]
    assert coupons[0] == 1.125 and coupons[-1] == 14.875
    for coupon in coupons:
        first_pos_rate = coupon / 100
        current_rate = first_pos_rate * 100  # gold: CAST(first_pos_rate * 100 AS DOUBLE)
        assert round(current_rate / 100.0, 7) == first_pos_rate, coupon


