ROOT = Path(__file__).resolve().parents[2]
UNIVERSAL_LOCK = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile requirements.in --universal --format requirements.txt -o uv.lock
aiohttp==3.14.5 \\
    --hash=sha256:0123456789abcdef
    # via -r requirements.in
numpy==1.26.4 ; python_full_version < '3.12'
numpy==2.1.0 ; python_full_version >= '3.12'
tomli==2.4.1 ; python_full_version < '3.11'
    # via coverage
Typing_Extensions==4.15.0    # via aiohttp
-e ./local-package
local-wheel @ https://example.invalid/local_wheel-1.0-py3-none-any.whl
"""


def _markers(**overrides: str) -> dict[str, str]:
    base = {str(k): str(v) for k, v in default_environment().items()}
    base.update({"python_version": "3.11", "python_full_version": "3.11.15",
                 "sys_platform": "linux", "platform_python_implementation": "CPython"})
    base.update(overrides)
    return base


def _env(
    installed: Mapping[str, str], requires: Mapping[str, Sequence[str]], **markers: str
) -> check.InstalledEnvironment:
    return check.InstalledEnvironment(
        markers=_markers(**markers),
        version=lambda name: installed.get(name),
        requires=lambda name: requires.get(name, []),
    )


def _pins(*lines: str) -> list[check.LockPin]:
    return check.parse_lock("\n".join(lines))


def test_the_real_lock_parses_into_the_deploy_preflight_pins() -> None:
    # Derived, not literal: a lock bump must not turn this red.
    text = (ROOT / "uv.lock").read_text(encoding="utf-8")
    pins = check.parse_lock(text)
    _, preflight = python_deps_check.parse_lock(text)

    assert len(pins) == len({p.name for p in pins}) > 100
    assert all(p.marker is None for p in pins)
    assert {p.name: p.version for p in pins} == preflight


PLATFORMS = {
    "linux-x86_64": {"sys_platform": "linux", "platform_system": "Linux", "platform_machine": "x86_64"},
    "macos-arm64": {"sys_platform": "darwin", "platform_system": "Darwin", "platform_machine": "arm64"},
}


@pytest.mark.parametrize("platform", PLATFORMS)
def test_the_real_lock_pins_the_closure_of_the_app_and_of_local_dev(platform: str) -> None:
    # 2026-10-28: the App (Linux x86_64) reported unpinned 1, greenlet, which
    # sqlalchemy requires on x86_64 but not on arm64, so a lock compiled on Apple
    # Silicon never pinned it. Replay a clean install of the lock on each platform:
    # every locked package at its pin, with the metadata this interpreter holds.
    text = (ROOT / "uv.lock").read_text(encoding="utf-8")
    pins = check.parse_lock(text)
    locked = {pin.name: pin.version for pin in pins}
    here = check.current_environment()
    env = check.InstalledEnvironment(
        markers=_markers(**PLATFORMS[platform]),
        version=lambda name: locked.get(name) or here.version(name),
        requires=here.requires,
    )

    result = check.compute_drift(
        pins, check.parse_requirements((ROOT / "requirements.in").read_text(encoding="utf-8")), env
    )

    assert (result.unpinned_names, result.drifted) == ((), ())
    assert ("greenlet" in result.not_applicable_names) is (platform == "macos-arm64")
    assert "--python-platform x86_64-manylinux_2_28" in text.splitlines()[1]


def test_a_universal_lock_keeps_markers_and_skips_hashes_options_and_urls() -> None:
    assert check.parse_lock(UNIVERSAL_LOCK) == [
        check.LockPin("aiohttp", "3.14.5"),
        check.LockPin("numpy", "1.26.4", "python_full_version < '3.12'"),
        check.LockPin("numpy", "2.1.0", "python_full_version >= '3.12'"),
        check.LockPin("tomli", "2.4.1", "python_full_version < '3.11'"),
        check.LockPin("typing-extensions", "4.15.0"),
    ]


def test_an_installed_closure_equal_to_the_lock_is_ok() -> None:
    # PEP 440 equality, as pip and the deploy preflight compare: 2.0 == 2.0.0.
    env = _env({"fastapi": "1.0", "starlette": "2.0"}, {"fastapi": ["starlette>=1"]})

    result = check.compute_drift(_pins("fastapi==1.0", "starlette==2.0.0"), ["fastapi==1.0"], env)

    assert (result.outcome, result.pins_checked, result.drifted) == ("ok", 2, ())


def test_a_stale_and_a_missing_package_are_drift_with_installed_null() -> None:
    env = _env({"fastapi": "1.0", "oauthlib": "3.3.1"}, {"fastapi": ["oauthlib", "starlette"]})

    result = check.compute_drift(
        _pins("fastapi==1.0", "oauthlib==4.0.0", "starlette==2.0"), ["fastapi"], env
    )

    assert result.outcome == "drift"
    assert result.drifted == (
        check.Drift("oauthlib", "4.0.0", "3.3.1"),
        check.Drift("starlette", "2.0", None),
    )


TOMLI_REQUIRES = {
    "pytest-cov": ["coverage[toml] >=7.5"],
    "coverage": ['tomli; python_full_version <= "3.11.0a6" and extra == "toml"'],
}


def test_a_lock_entry_excluded_by_its_parents_marker_is_not_applicable() -> None:
    # The real lock pins tomli via coverage[toml]; on Python 3.11 nothing installs it.
    pins = _pins("pytest-cov==6.0.0", "coverage==7.10.0", "tomli==2.4.1")
    installed = {"pytest-cov": "6.0.0", "coverage": "7.10.0"}

    on_311 = check.compute_drift(pins, ["pytest-cov"], _env(installed, TOMLI_REQUIRES))
    on_310 = check.compute_drift(
        pins, ["pytest-cov"],
        _env(installed, TOMLI_REQUIRES, python_version="3.10", python_full_version="3.10.14"),
    )

    assert (on_311.outcome, on_311.pins_checked, on_311.not_applicable) == ("ok", 2, 1)
    assert on_311.not_applicable_names == ("tomli",)
    assert on_310.drifted == (check.Drift("tomli", "2.4.1", None),)


@pytest.mark.parametrize("reverse", [False, True])
def test_a_pin_line_marker_selects_the_pin_for_this_interpreter(reverse: bool) -> None:
    lines = UNIVERSAL_LOCK.splitlines()
    numpy = [i for i, line in enumerate(lines) if line.startswith("numpy==")]
    if reverse:
        lines[numpy[0]], lines[numpy[1]] = lines[numpy[1]], lines[numpy[0]]
    # tomli's pin applies only below 3.11: here it is installed off-pin yet unpinned.
    env = _env({"numpy": "2.1.0", "tomli": "2.0.0"}, {})

    result = check.compute_drift(check.parse_lock("\n".join(lines)), ["numpy", "tomli"], env)

    assert result.drifted == (check.Drift("numpy", "1.26.4", "2.1.0"),)
    # numpy 2.1.0 and tomli by marker; aiohttp and typing-extensions unreached.
    assert (result.not_applicable, result.unpinned) == (4, 1)
    # Lines are counted, packages named: numpy's 1.26.4 line applied, so it is not named.
    assert result.not_applicable_names == ("aiohttp", "tomli", "typing-extensions")
    assert result.unpinned_names == ("tomli",)


def test_platform_only_dependencies_follow_this_platform() -> None:
    pins = _pins("uvicorn==0.47.0", "uvloop==0.22.1", "colorama==0.4.6", "pywin32==311")
    roots = ["uvicorn[standard]", "pywin32==311; sys_platform == 'win32'"]
    requires = {"uvicorn": [
        "colorama>=0.4; (sys_platform == 'win32') and extra == 'standard'",
        "uvloop>=0.15.1; (sys_platform != 'win32') and extra == 'standard'",
    ]}
    installed = {"uvicorn": "0.47.0", "uvloop": "0.22.1"}

    linux = check.compute_drift(pins, roots, _env(installed, requires))
    windows = check.compute_drift(pins, roots, _env(installed, requires, sys_platform="win32"))

    assert (linux.outcome, linux.pins_checked, linux.not_applicable) == ("ok", 2, 2)
    assert linux.not_applicable_names == ("colorama", "pywin32")
    assert windows.drifted == (
        check.Drift("colorama", "0.4.6", None),
        check.Drift("pywin32", "311", None),
    )


