"""The deploy interpreter: MIP_DEPLOY_PYTHON and the requirements.txt pin check.

full_deploy_readiness.md 3.12 and its adversarial C3: deploy.sh used
``.venv/bin/python`` or a bare ``python3`` with no override, and checked only
``import boto3, mlflow``, so a drifted mlflow / databricks-sdk /
databricks-sql-connector could register and serve a stack CI never proved.
tools/python_deps_check.py walks the installed closure of requirements.in and
compares it with uv.lock; deploy.sh step 0 refuses drift with exit 2 in a real
run. The shell blocks are read from ``deploy_entrypoint_text()`` (the sliced
deploy.sh layout) and driven in small harnesses.
"""

