def test_a_real_deploy_with_a_drifted_override_stops_at_step_0_before_any_workspace_call(
    tmp_path: Path,
) -> None:
    repo = tmp_path / "repo"
    (repo / "scripts" / "lib").mkdir(parents=True)
    shutil.copy2(DEPLOY_SCRIPT, repo / "scripts" / "deploy.sh")
    for source in DEPLOY_SOURCED_SCRIPTS:
        shutil.copy2(source, repo / "scripts" / "lib" / source.name)
    (repo / "tools").mkdir()
    shutil.copy2(TOOL, repo / "tools" / "python_deps_check.py")
    # The client profile resolves before the pin check (M1-PR2): carry its
    # resolver and a synthetic profile, so the run reaches the check.
    shutil.copytree(ROOT / "tools" / "clients", repo / "tools" / "clients", ignore=shutil.ignore_patterns("__pycache__"))
    (repo / "tools" / "__init__.py").write_text("", encoding="utf-8")
    (repo / "backend" / "schemas").mkdir(parents=True)
    # The profile's lender pin rules import the record module (#298), which
    # imports the branding rules.
    for module in (
        "__init__.py",
        "schemas/__init__.py",
        "schemas/lender_identity.py",
        "schemas/lender_identity_record.py",
        "schemas/lender_branding.py",
    ):
        shutil.copy2(ROOT / "backend" / module, repo / "backend" / module)
    _repo(tmp_path, requirements_in="pytest\n", lock={"pytest": "0.0.1"})
    (repo / "databricks.yml").write_text("targets:\n  client: {}\n", encoding="utf-8")
    (repo / ".gitignore").write_text(".env.local\n__pycache__/\n", encoding="utf-8")
    (repo / ".env.local").write_text(
        env_file_text({**paychex_shaped_profile(), "DATABRICKS_TOKEN": "reviewed-pat"}),
        encoding="utf-8",
    )
    git = ["git", "-c", "user.name=Deploy Test", "-c", "user.email=deploy-test@example.com"]
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "add", "-A"], cwd=repo, check=True)
    subprocess.run([*git, "commit", "-qm", "fixture"], cwd=repo, check=True)
    bin_dir = tmp_path / "bin"
    log = tmp_path / "databricks.log"
    _executable(
        bin_dir / "databricks",
        f'#!/usr/bin/env bash\nprintf "%s\\n" "$*" >> {shlex.quote(str(log))}\necho "Databricks CLI v-test"\n',
    )
    env = {
        name: value
        for name, value in os.environ.items()
        if not name.startswith(("DATABRICKS_", "MIP_", "COV_CORE", "COVERAGE"))
    }
    env.update(
        {
            "PATH": f"{bin_dir}{os.pathsep}{os.environ.get('PATH', '')}",
            "HOME": str(tmp_path),
            "MIP_DEPLOY_PYTHON": sys.executable,
        }
    )

    result = subprocess.run(
        ["bash", "scripts/deploy.sh", "-t", "client", "--no-confirm"],
        cwd=repo,
        env=env,
        text=True,
        capture_output=True,
        check=False,
        timeout=120,
    )

    assert result.returncode == 2, result.stdout + result.stderr
    assert f"  python:     {sys.executable}" in result.stdout
    assert "  drift: pytest installed " in result.stdout
    assert "export MIP_DEPLOY_PYTHON=" in result.stdout
    assert "python deps: drifted" in result.stdout
    assert "does not match the requirements.txt pins" in result.stderr
    assert log.read_text(encoding="utf-8").splitlines() == ["--version"], "no workspace call"
    assert "step 2:" not in result.stdout
