# ----------------------------------------------------- the MIP_DEPLOY_PYTHON override


def _interp_harness(cwd: Path, value: str | None) -> subprocess.CompletedProcess[str]:
    script = cwd / "resolve.sh"
    script.write_text(
        'set -euo pipefail\nRED=""\nRST=""\n'
        f"{_block(INTERP_START, INTERP_END)}\n"
        'printf "PYTHON=%s\\n" "$PYTHON"\n',
        encoding="utf-8",
    )
    env = {"PATH": os.environ.get("PATH", ""), "HOME": str(cwd)}
    if value is not None:
        env["MIP_DEPLOY_PYTHON"] = value
    return subprocess.run(["bash", str(script)], cwd=cwd, env=env, text=True, capture_output=True, check=False)


def _executable(path: Path, body: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    path.chmod(0o755)
    return path


def test_the_override_sits_in_the_entrypoint_before_any_python_use() -> None:
    # The raw file, not deploy_entrypoint_text(), on purpose: the block must live in
    # deploy.sh itself, ahead of the first sourced lib, which the expansion would hide.
    entrypoint = DEPLOY_SCRIPT.read_text(encoding="utf-8")

