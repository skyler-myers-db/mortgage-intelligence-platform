def _block(start: str, end: str) -> str:
    text = deploy_entrypoint_text()
    assert text.count(start) == 1 and text.count(end) == 1
    return text[text.index(start) : text.index(end) + len(end)]


def _step_body_start(step_file: str) -> str:
    text = (ROOT / "scripts" / "lib" / step_file).read_text(encoding="utf-8")
    return text[text.index("\n\n") + 2 :][:200]


def test_the_pin_check_runs_before_any_workspace_call_prompt_or_mutation() -> None:
    text = deploy_entrypoint_text()
    check = text.index(PINS_START)

    assert text.index('echo "  python:     ${PYTHON}"') < check
    assert check < text.index("import boto3, mlflow")
    assert check < text.index("workspace_admin_inventory_principal(WorkspaceClient())")
    assert check < text.index(PROMPT) < text.index("\nrun ")
    assert check < text.index('step "acquire signed workspace lease for the exact App deployment"')
    assert check < text.index(_step_body_start("deploy_step_signed_blue_proof.sh")), "before the App stop"


def test_the_pin_check_block_never_installs_and_refuses_only_real_runs() -> None:
    block = _block(PINS_START, PINS_END)
    code = "\n".join(line for line in block.splitlines() if not line.lstrip().startswith("#"))

    assert "pip " not in code and "install" not in code
    assert 'if [[ "$DRY_RUN" -eq 0 && "$PYTHON_DEPS_STATE" != "pinned" ]]; then' in code
    assert code.count("exit 2") == 1


def _pins_harness(repo: Path, *, dry_run: int, tool_exit: int | None) -> subprocess.CompletedProcess[str]:
    if tool_exit is not None:
        (repo / "tools").mkdir(parents=True, exist_ok=True)
        (repo / "tools" / "python_deps_check.py").write_text(
            f"import sys\nprint('  stub verdict')\nsys.exit({tool_exit})\n",
            encoding="utf-8",
        )
    script = repo / "preflight.sh"
    script.write_text(
        "set -euo pipefail\n"
        f'RED=""\nRST=""\nDRY_RUN={dry_run}\nTARGET=dev\nPYTHON={shlex.quote(sys.executable)}\n'
        f"{_block(PINS_START, PINS_END)}\necho reached-after-block\n",
        encoding="utf-8",
    )
    env = {"PATH": os.environ.get("PATH", ""), "HOME": str(repo)}
    return subprocess.run(["bash", str(script)], cwd=repo, env=env, text=True, capture_output=True, check=False)


def test_a_pinned_interpreter_passes_a_real_run(tmp_path: Path) -> None:
    result = _pins_harness(tmp_path, dry_run=0, tool_exit=0)

    assert result.returncode == 0, result.stderr
    assert "python deps: pinned" in result.stdout and "reached-after-block" in result.stdout


