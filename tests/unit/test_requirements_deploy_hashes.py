"""requirements-deploy.hashes.txt is uv.lock with hashes, for the deploy job's offline install (M1-PR7).

deploy-dev.yml's ``build`` job (no id-token) downloads a wheelhouse from this
file, and its ``deploy`` job (id-token: write) installs from that wheelhouse
only: ``pip install --no-index --find-links <wheelhouse> --require-hashes``.
So the file must pin exactly uv.lock's closure, the App runtime and nothing
else (never the dev tools), for the App's platform, and every pin must carry
its sha256 hashes. A uv.lock refresh without a regenerated hashes file fails
here: regenerate it with the command in its header (docs/deployment.md,
"App Python dependencies: the deploy job's hashed install").
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from tools.deps_report.python import pep503, pins

ROOT = Path(__file__).resolve().parents[2]
HASHES = ROOT / "requirements-deploy.hashes.txt"
UV_LOCK = ROOT / "uv.lock"
DEPLOY_COMPILE = (
    "uv pip compile requirements.in -c uv.lock --python-version 3.11 "
    "--python-platform x86_64-manylinux_2_28 --generate-hashes --format requirements.txt "
    "--output-file requirements-deploy.hashes.txt"
)
DEV_TOOLS = ("pytest", "pytest-cov", "pytest-xdist", "ruff", "mypy", "hypothesis")
_PIN_LINE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==([^\s;\\]+)(?:\s*;[^\\]*)?\s*\\$")
_HASH_LINE = re.compile(r"^    --hash=sha256:[0-9a-f]{64}(?: \\)?$")


def _blocks() -> dict[str, list[str]]:
    """Each pin's hash lines, by normalized name; refuses any other requirement shape."""

    found: dict[str, list[str]] = {}
    current: str | None = None
    for number, line in enumerate(HASHES.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            current = None
            continue
        if line.startswith("    --hash="):
            assert current is not None and _HASH_LINE.fullmatch(line), f"line {number}: a stray or malformed hash"
            found[current].append(line)
            continue
        match = _PIN_LINE.fullmatch(line)
        assert match, f"line {number}: only name==version pins with hashes, no option, URL or editable"
        current = pep503(match.group(1))
        assert current not in found, f"line {number}: {current} is pinned twice"
        found[current] = []
    return found


def test_the_header_records_the_one_compile_command() -> None:
    lines = HASHES.read_text(encoding="utf-8").splitlines()
    assert lines[0] == "# This file was autogenerated by uv via the following command:"
    assert lines[1] == f"#    {DEPLOY_COMPILE}"
    # The App runtime only, for the App's platform; never the dev tools.
    assert "requirements-dev" not in lines[1]


def test_the_hashes_file_pins_exactly_the_uv_lock_closure() -> None:
    assert pins(HASHES) == pins(UV_LOCK), "regenerate requirements-deploy.hashes.txt with its header command"
    assert not set(DEV_TOOLS) & set(pins(HASHES)), "the dev tools never reach the deploy job"


def test_every_pin_carries_sha256_hashes_and_nothing_else_reaches_pip() -> None:
    blocks = _blocks()
    assert set(blocks) == set(pins(UV_LOCK))
    assert all(blocks.values()), sorted(name for name, hashes in blocks.items() if not hashes)
    for name, hashes in blocks.items():
        assert hashes[-1].endswith(tuple("0123456789abcdef")), f"{name}: its last hash ends the requirement"
        assert all(line.endswith(" \\") for line in hashes[:-1]), f"{name}: a hash line breaks the requirement"


def test_the_control_parser_refuses_an_unhashed_or_optioned_line(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Non-vacuity: the block parser fails on the shapes it exists to refuse."""

    import tests.unit.test_requirements_deploy_hashes as module

    for bad in ("--index-url https://example.invalid/simple\n", "fastapi==0.136.1\n", "-e .\n"):
        path = tmp_path / "bad.txt"
        path.write_text(bad, encoding="utf-8")
        monkeypatch.setattr(module, "HASHES", path)
        try:
            blocks = module._blocks()
        except AssertionError:
            continue
        assert not all(blocks.values()), bad
