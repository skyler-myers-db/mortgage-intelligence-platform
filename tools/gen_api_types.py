#!/usr/bin/env python3
"""Emit frontend/src/types/api.gen.ts from the committed OpenAPI baseline.

Usage:
    python tools/gen_api_types.py --write    # rewrite the TS module
    python tools/gen_api_types.py --check    # exit 1 when the TS module is stale

The input is ``tests/fixtures/openapi_baseline.json``, which
test_openapi_baseline_captures_current_api_surface already pins to the live
app; this tool never imports the backend. ``python
tools/regen_openapi_baseline.py`` rewrites both files in one run.

The output is one type-only module with three parts:

1. ``ResponseSchemas``: the 2xx closure in the PRESENCE view. FastAPI
   serializes every declared field, so every declared property is present
   (``name: T``); nullability comes only from an ``anyOf`` with ``null``. The
   $ref closure of ABSENT_KEY_ROOTS (routes serialized with
   ``response_model_exclude_unset``) keeps its declared ``required`` list.
2. ``RequestSchemas``: the request-body and parameter closure in the DECLARED
   view (``required`` as declared, ``?:`` otherwise).
3. ``ApiOperations``: the canonical ``/api/v1`` operations with their path,
   query and header parameters, body and 2xx ``ok`` union.

Everything is closed and fails closed: exactly the 22 JSON Schema keywords the
baseline uses, three formats, five parameter-object keys, a reviewed header
allowlist (cookies refused), and a content screen over every emitted
description and string literal. A construct outside those sets raises
UnsupportedSchema with its JSON pointer; extend the sets only with a reviewed
golden case in tests/unit/test_api_types_generator.py.

Python 3.11 standard library only: this module imports neither ``backend``
nor any other ``tools`` module.
"""

